[CmdletBinding()]
param([Parameter(Mandatory)][string] $DataDirectory)
$ErrorActionPreference = 'Stop'
# Explicit maintenance command only. Build/test/publish never download Unicode data.
# Inputs: https://www.unicode.org/Public/17.0.0/ucd/EastAsianWidth.txt
# https://www.unicode.org/Public/17.0.0/ucd/emoji/emoji-data.txt
# https://www.unicode.org/license.txt (captured 2026-09-09)
$hashes = @{
    'EastAsianWidth.txt' = 'EA7CE50F3444A050333448DFFEF1CADD9325AF55CBB764B4A2280FAF52170A33'
    'emoji-data.txt' = '2CB2BB9455CDA83E8481541ECF5B6DFDA66A3BB89EFA3FA7C5297ECCF607B72B'
    'LICENSE.txt' = 'E7A93B009565CFCE55919A381437AC4DB883E9DA2126FA28B91D12732BC53D96'
}
foreach ($name in $hashes.Keys) {
    if ((Get-FileHash -LiteralPath (Join-Path $DataDirectory $name)).Hash -ne $hashes[$name]) { throw "Unicode input hash mismatch: $name" }
}
function Ranges([string] $File, [string[]] $Properties) {
    $ranges = [Collections.Generic.List[object]]::new()
    foreach ($line in [IO.File]::ReadLines((Join-Path $DataDirectory $File))) {
        if ($line -notmatch '^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)') { continue }
        if ($Matches[3] -notin $Properties) { continue }
        $start = [Convert]::ToInt32($Matches[1], 16)
        $end = if ($Matches[2]) { [Convert]::ToInt32($Matches[2], 16) } else { $start }
        if ($ranges.Count -gt 0 -and $ranges[$ranges.Count-1].End + 1 -eq $start) { $ranges[$ranges.Count-1].End = $end }
        else { $ranges.Add([pscustomobject]@{ Start=$start; End=$end }) }
    }
    ($ranges | ForEach-Object { '        (0x{0:X}, 0x{1:X}),' -f $_.Start,$_.End }) -join "`n"
}
$license = [IO.File]::ReadAllText((Join-Path $DataDirectory 'LICENSE.txt')).Replace("`r`n", "`n")
$wide = Ranges 'EastAsianWidth.txt' @('W', 'F')
$emoji = Ranges 'emoji-data.txt' @('Emoji')
$presentation = Ranges 'emoji-data.txt' @('Emoji_Presentation')
$text = @"
// Generated by src/Generate-UnicodeWidth.ps1 from the hash-checked Unicode 17.0.0 inputs.
// Unicode data license retained below. No network access is needed at build/run time.
/*
$license
*/
namespace Dert.Text;

internal static class UnicodeWidthData
{
    internal static readonly (int First, int Last)[] Wide = [
$wide
    ];
    internal static readonly (int First, int Last)[] Emoji = [
$emoji
    ];
    internal static readonly (int First, int Last)[] EmojiPresentation = [
$presentation
    ];
}
"@
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'Dert.Text/UnicodeWidthData.cs'), $text.Replace("`r`n", "`n") + "`n", [Text.UTF8Encoding]::new($false))
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'Dert.Text/UNICODE-LICENSE.txt'), $license, [Text.UTF8Encoding]::new($false))
Write-Host 'Generated Unicode 17.0.0 width and emoji tables from verified local inputs.'
